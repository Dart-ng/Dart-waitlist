CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  password_hash TEXT,
  password_salt TEXT,
  interest TEXT NOT NULL,
  queue_number INTEGER NOT NULL UNIQUE,
  referral_code TEXT NOT NULL UNIQUE,
  referred_by INTEGER REFERENCES users(id),
  referral_count INTEGER NOT NULL DEFAULT 0,
  ip_hash TEXT,
  role TEXT NOT NULL DEFAULT 'member',
  created_at TEXT NOT NULL,
  google_sub TEXT,
  google_picture_url TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_case_insensitive_unique
  ON users (lower(email));
CREATE UNIQUE INDEX IF NOT EXISTS users_referral_code_case_insensitive_unique
  ON users (lower(referral_code));
CREATE UNIQUE INDEX IF NOT EXISTS users_google_sub_unique
  ON users (google_sub)
  WHERE google_sub IS NOT NULL;

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS oauth_states (
  state_hash TEXT PRIMARY KEY,
  referral_code TEXT,
  expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS announcements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message TEXT NOT NULL,
  created_at TEXT NOT NULL
);
